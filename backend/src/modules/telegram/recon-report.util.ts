// Классификатор «чистых» дорозвідка-отчётов.
//
// Каналы мониторинга публикуют служебные сводки вида
// «Київ та область дорозвідка до відбою», «Київщина дорозвідка»,
// «дорозвідка по Бандеролях». Это НЕ угрозы — они не должны уходить
// в LLM и не должны порождать оверлеи на карте.
//
// Сообщения, где «дорозвідка» идёт вместе с реальной угрозой
// (мгКР, ракеты, баллистика, взлёт авиации и т.п.), анализируются как обычно —
// в этом случае LLM должен брать из поста только боевую часть (см. промпт).

const RECON_PATTERN = /дорозвідк/i;

// Признаки реальной угрозы. Внимательно: «БпЛА», «Бандеролі»
// сюда НЕ входят — они часто встречаются внутри чистых дорозвідка-отчётов
// («дорозвідка БПЛА», «дорозвідка по Бандеролях»). А вот «реактив» входит:
// «2х реактиви повз Славутич» — это реальная угроза, даже если пост
// начинался с «дорозвідка».
const STRIKE_KEYWORD_PATTERN =
  /мгКР|крилат|ракет|баліст|іскандер|кинджал|циркон|шахед|пуски?|удар|увага по|міг-31|ту-22|ту-95|ту-160|су-34|су-25|су-35|зліт|авіац|реактив|вибух|🅿/i;

export function isReconOnlyReport(text: string): boolean {
  return RECON_PATTERN.test(text) && !STRIKE_KEYWORD_PATTERN.test(text);
}
